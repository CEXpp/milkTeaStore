/**
 * 取餐提醒的触觉信道（T45，SRS 9.6「双信道取餐提醒」）。
 *
 * <h2>为什么需要它</h2>
 * 柜台取餐场景的传统做法是「店员喊号」，这对听障顾客天然失效（任务卡：「听障顾客取餐提醒靠
 * 视觉 + 手机震动，不依赖柜台喊号」）。因此「请取餐」这条信息必须至少有两条独立信道：
 * <ol>
 *   <li><b>视觉</b>：页面横幅 + 大号取餐码（无障碍模式下进一步放大加黑）；</li>
 *   <li><b>触觉</b>：本模块的手机震动；</li>
 *   <li><b>离线</b>：微信订阅消息（T44）——顾客退出小程序、屏幕熄灭时仍能收到。</li>
 * </ol>
 *
 * <p>三者的<b>触发条件完全同源</b>：都由「订单进入 COMPLETED（PICKUP_READY）」这一条事件驱动
 * （LLD 11.4：「两信道内容同源，不重复造数」），不存在各自判定导致的「消息到了但页面没变」。</p>
 *
 * <p><b>降级</b>：宿主不支持震动（H5 / 部分设备）、用户系统级关闭震动——一律静默忽略；
 * 视觉与订阅消息信道不受影响（SRS 9.3）。</p>
 */

/**
 * 取餐就绪的长震动提醒（震动时长由系统决定）。
 *
 * <p>用长震动而非短震动：取餐是「需要用户起身动作」的事件，长震动更容易被注意到，
 * 与开关切换用的短震动（{@code stores/a11y.ts}）在体感上明确区分。</p>
 */
export function vibratePickupReady(): void {
  try {
    uni.vibrateLong({ fail: () => undefined })
  } catch {
    // 忽略：震动只是增强信道
  }
}
