/**
 * 职责域：notify —— 顾客离线通知（T44，A4c 微信订阅消息推送）。
 *
 * <p>最关键的设计决策：<b>订阅消息是 SSE 的离线补位，不是第二套事件</b>。
 * 在线顾客由 SSE 通道（T43）实时可见；离线顾客只能靠微信订阅消息触达。
 * 两者消费同一份 {@code OrderEvent}（经 {@link com.milktea.order.order.event.OrderEventListener}
 * 扩展点接入），因此状态口径天然一致，不会出现「页面显示请取餐、消息说还在制作」
 * （LLD 11.4：「两信道内容同源，不重复造数」）。</p>
 *
 * <p><b>微信「一次性订阅」语义</b>（官方契约，非推测）：用户授权一次 = 服务端可下发一条；
 * 次数用尽后再下发会返回 {@code errcode=43101}。故本包以 {@code wx_subscribe_quota} 表
 * 记录「剩余可下发次数」（授权 +1、成功下发 -1），任务卡验收项「同一次订阅不重复推送」
 * 由此落地；「用户拒绝授权」表现为额度始终为 0，下发路径直接短路，不影响主链路。</p>
 *
 * <p><b>降级</b>（SRS 9.3）：未配置 AppSecret 或模板 ID 时全链路静默跳过；下发失败仅记日志，
 * 不抛出、不回滚订单事务——推送永远不能让「出餐」这个动作失败。</p>
 */
