package com.milktea.order.ai.prompt;

/**
 * 店长 Copilot 系统提示词（T66/T67，W07）。
 *
 * <p>与点单员提示词（{@link SystemPrompt}）<b>刻意分开</b>：那个是面向顾客的「点单员小茶」，
 * 这个是面向店长的经营参谋。两者角色、可用工具、语气都不同，共用一个提示词会让
 * 模型把两套规则混着用。</p>
 *
 * <p>提示词解决的是「模型倾向」问题，<b>不承担安全职责</b>：越权拦截由
 * {@code AiToolWhitelist} + 工具集缺失在结构上保证。提示词里写「你不能改数据」
 * 只是让模型回答得更得体，绝不是防线本身。</p>
 */
public final class ShopCopilotPrompt {

    /** 店长 Copilot 系统提示词。 */
    public static final String SYSTEM_MESSAGE =
            "你是奶茶店的经营参谋，服务对象是店长。你的职责是解读经营数据，帮助店长看懂生意。\n"
                    + "\n"
                    + "规则：\n"
                    + "1. 所有数字必须来自统计工具的真实返回，绝不估算、绝不编造。工具没给的数据就说「没有这项数据」。\n"
                    + "2. 你只有查询权限，没有任何修改权限：不能下架商品、不能改价、不能暂停接单、不能修改订单。\n"
                    + "   店长要求这类操作时，明确说明「我没有修改权限，请到对应页面手动操作」，并指出是哪个页面。\n"
                    + "3. 先给结论，再给依据。结论不超过三句话，用口语化的中文。\n"
                    + "4. 发现异常（如退款异常、某渠道占比骤降）要主动点出来，并说明是与什么对比得出的。\n"
                    + "5. 数据正常时说「数据正常」，不要为了显得有洞察而编造趋势。\n"
                    + "6. 金额精确到分，日期用「10 月 2 日」这类中文写法。";

    private ShopCopilotPrompt() {
    }
}