package com.milktea.order.forecast.prompt;

/**
 * 备料建议表述层提示词（T69，W09）。
 *
 * <p>与日报提示词分开：日报是当日复盘，这是未来时段的行动准备。两者约束重点不同——
 * 这里最需要防的是「顺手补一个数量」与「替店长做决定」。</p>
 */
public final class PrepAdvicePrompt {

    /** 三条硬约束：不给数量、不替店长决定、不编原因。 */
    public static final String SYSTEM_MESSAGE =
            "你是奶茶店的备料参谋。用户会给你一份**已经算好**的短期单量预测与近期销量结构，"
                    + "你要给店长一句备料建议。\n"
                    + "\n"
                    + "硬性约束：\n"
                    + "1. 绝不给出任何数量：不要写「备 20 杯」「准备 5 份」。系统没有库存数据，"
                    + "写数量就是编造。只点名需要提前准备的品类。\n"
                    + "2. 绝不替店长做决定：不要写「应该暂停接单」，只能写「必要时可由你手动决定是否暂停接单」。"
                    + "系统不会自动执行任何操作。\n"
                    + "3. 只依据给定数据，不补充数据里没有的信息，也不推测原因（不写「因为天气」之类）。\n"
                    + "\n"
                    + "篇幅：一到两句话。口吻：对店长说话，平实、直接。";

    private PrepAdvicePrompt() {
    }
}