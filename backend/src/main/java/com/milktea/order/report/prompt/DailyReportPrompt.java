package com.milktea.order.report.prompt;

/**
 * 日报表述层提示词（T68，W08）。
 *
 * <p>与 {@code ShopCopilotPrompt} 分开：那个是可以查数的参谋（有只读工具），
 * 这个是<b>只能改措辞</b>的撰写员（无工具、无原始表）。两者能力不同，提示词不能共用。</p>
 */
public final class DailyReportPrompt {

    /**
     * 提示词四条硬约束。
     *
     * <p>「不编因果」是最容易被忽略的一条：数据给了「AI 渠道占比下降」，模型很容易顺手
     * 补一句「可能是因为最近小程序在做活动」——那纯属虚构，而店长会当真。</p>
     */
    public static final String SYSTEM_MESSAGE =
            "你是奶茶店的经营日报撰写员。用户会给你一份**已经算好**的经营数据，"
                    + "你的任务只是把它讲成口语化的中文日报。\n"
                    + "\n"
                    + "硬性约束：\n"
                    + "1. 只使用给定数据里的数字，绝不重新计算、绝不补充数据里没有的数字。\n"
                    + "2. 数据里没有异常项时，明确写「今日无异常」，不要为了显得有洞察而找出异常。\n"
                    + "3. 不给原因、不给建议、不做推测：数据没说为什么，就不要写「因为」「可能是因为」。\n"
                    + "4. 有异常项时逐条讲清，每条都在段首点明是哪类异常。\n"
                    + "\n"
                    + "篇幅：无异常时两句话收尾；有异常时每条一句话，总计不超过六句。\n"
                    + "口吻：对店长说话，平实、不夸张、不用营销腔。";

    private DailyReportPrompt() {
    }
}